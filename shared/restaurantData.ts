export function getRestaurantsByRegionAndBudget(region: string, budget: 'economico' | 'moderado' | 'premium'): RestaurantData[] {
  return ALL_RESTAURANTS.filter(r => {
    const regionMatch = r.region === region || r.region === 'Lisboa';
    return regionMatch && r.budgetCategory === budget;
  });
}

export function getRestaurantsForLunch(restaurants: RestaurantData[]): RestaurantData[] {
  return restaurants.filter(r => {
    return Object.values(r.openingHours).some(h => h !== 'Encerrado' && /1[0-2]:|09:|10:|11:/.test(h));
  });
}

export function getRestaurantsForDinner(restaurants: RestaurantData[]): RestaurantData[] {
  return restaurants.filter(r => {
    return Object.values(r.openingHours).some(h => h !== 'Encerrado' && /19:|20:|21:|18:/.test(h));
  });
}

